import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const output = process.env.PEOPLE_SCREENSHOT_DIR ? new URL('file:///' + process.env.PEOPLE_SCREENSHOT_DIR.replaceAll('\\', '/').replace(/\/$/, '') + '/') : new URL('../.people-test-output/', import.meta.url);
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : { channel: 'chrome' }), headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1060 } });
page.setDefaultTimeout(12000);
const errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto('http://127.0.0.1:3000/people/preview');
  await page.getByRole('heading', { name: 'Good morning, Sarah.' }).waitFor();
  assert.equal(await page.getByRole('navigation', { name: 'Workspace' }).getByRole('button').count(), 2, 'Only Home and People & roles belong in the workspace navigation');
  await page.getByRole('button', { name: 'People & roles' }).click();
  await page.getByRole('region', { name: 'Person details' }).waitFor();
  await page.screenshot({ path: new URL('HandsIn-People-Desktop.png', output).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  await page.getByRole('tab', { name: 'Access', exact: true }).click();
  await page.getByRole('button', { name: 'Configure regular access' }).click();
  await page.getByRole('dialog').getByRole('button', { name: /Tier 3 Full access/ }).click();
  await page.getByRole('button', { name: 'Save preview access' }).click();
  // James is still Tier 2 during his vacation because temporary access replaces regular access.
  assert.match(await page.getByRole('region', { name: 'Person details' }).innerText(), /Tier 2/);
  await page.getByRole('button', { name: 'Invite someone' }).click();
  await page.getByLabel('Name', { exact: true }).fill('Avery Test');
  await page.getByLabel('Invited email').fill('avery@example.test');
  await page.getByText('Advanced configuration', { exact: false }).click();
  await page.getByLabel('Health reports', { exact: true }).check();
  await page.getByRole('button', { name: 'Prepare preview invitation' }).click();
  await page.getByText('Avery Test', { exact: true }).waitFor();
  await page.getByLabel('Preview persona').selectOption('james');
  await page.getByRole('button', { name: 'Home', exact: true }).click();
  assert.equal(await page.getByRole('heading', { name: 'Review new blood test report' }).count(), 0);
  const lunch = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Make lunch together' }) });
  await lunch.getByRole('button', { name: 'Accept assignment' }).click();
  await lunch.getByRole('button', { name: 'Mark complete' }).click();
  assert.match(await lunch.innerText(), /Completed/);
  await page.getByRole('button', { name: 'Create subgroup', exact: true }).click();
  await page.getByLabel('Subgroup name').fill('Saturday visit');
  await page.getByLabel('What’s this group for?').fill('Fictional family visit.');
  await page.getByLabel('Starts · device timezone').fill('2026-11-14T08:00');
  await page.getByLabel('Ends · device timezone').fill('2026-11-20T18:00');
  await page.getByRole('button', { name: 'Request approval' }).click();
  await page.getByText('Needs approval', { exact: true }).waitFor();
  await page.getByLabel('Preview persona').selectOption('sarah');
  await page.getByRole('button', { name: 'Approve subgroup' }).click();
  assert.equal(await page.getByText('Needs approval', { exact: true }).count(), 0);
  await page.getByLabel('Preview persona').selectOption('maya');
  await page.getByRole('button', { name: 'Home', exact: true }).click();
  assert.equal(await page.getByRole('heading', { name: 'Review new blood test report' }).count(), 0);
  await page.getByRole('button', { name: 'Accept assignment' }).click();
  await page.getByRole('button', { name: 'Record medication outcome' }).click();
  await page.getByRole('button', { name: 'Uncertain', exact: true }).click();
  await page.getByText('Caregiver recorded: uncertain', { exact: true }).waitFor();
  await page.getByLabel('Preview persona').selectOption('sarah');
  await page.getByRole('button', { name: 'End temporary access now' }).first().click();
  await page.getByLabel('Preview persona').selectOption('maya');
  await page.getByRole('heading', { name: 'You don’t have access to Margaret.' }).waitFor();
  await page.getByLabel('Preview persona').selectOption('james');
  await page.getByRole('button', { name: /People & roles/ }).click();
  assert.match(await page.getByRole('region', { name: 'Person details' }).innerText(), /Tier 3/);
  // Fresh mobile session, no state carried from the above tests.
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await page.getByRole('button', { name: /People & roles/ }).click();
  await page.getByRole('heading', { name: 'Your people.' }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'Mobile page must not overflow horizontally');
  await page.screenshot({ path: new URL('HandsIn-People-Mobile.png', output).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  await page.getByRole('button', { name: 'Invite someone' }).click();
  assert.equal(await page.getByRole('dialog').isVisible(), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Passed: roster, tier override, advanced invite, assignment acceptance/completion, subgroup approval, two-section navigation, medication outcome, expiry, regular-tier restoration, mobile layout, dialog dismissal, no browser errors.');
} catch (error) {
  console.error((await page.locator('body').innerText()).slice(-2200));
  throw error;
} finally { await browser.close(); }
